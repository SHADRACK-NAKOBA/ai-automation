if __name__ == "__main__":
    import sys

    config = get_config()
    agent = LogHarvester(config)

    if len(sys.argv) > 1 and sys.argv[1] == "--test":
        agent.run_test()

    elif len(sys.argv) > 1 and sys.argv[1] == "--ticket":
        if len(sys.argv) < 3:
            print("Usage: python agents/log_harvester.py --ticket INC0000018")
            sys.exit(1)
        ticket_number = sys.argv[2]
        tickets = agent.snow.get_incidents(
            query=f"number={ticket_number}",
            limit=1
        )
        if not tickets:
            print(f"Ticket not found: {ticket_number}")
            sys.exit(1)
        agent.process_incident(tickets[0]["sys_id"])

    else:
        stats = agent.process_recent_p1_p2()
        logger.info(f"Batch complete: {stats}")