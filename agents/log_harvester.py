"""
agents/log_harvester.py
========================
Agent #2: Log Harvester and Summarizer

WHAT IT DOES:
  When a P1 or P2 ticket is created, automatically fetches logs
  from monitoring tools, runs them through Claude, and attaches
  a plain-English Log Brief to the ticket within 90 seconds.

WHY THIS AGENT:
  Analysts spend 15-25 minutes hunting logs on every P1/P2.
  This eliminates that entirely.
  Time saved: 18 minutes per incident.
"""

import json
import time
from datetime import datetime, timezone
from pathlib import Path

import anthropic
import requests

from shared.config import get_config
from shared.snow_client import ServiceNowClient
from shared.data_sanitizer import sanitize_log
from shared.metrics_db import MetricsDB
from shared.logger import get_logger

logger = get_logger("log_harvester")

MINUTES_SAVED_PER_RUN = 18.0


def load_synthetic_logs(service_name: str = "") -> list:
    """Load synthetic log entries for testing without real monitoring tools."""
    path = Path("data/synthetic/logs.json")
    if not path.exists():
        logger.warning("No synthetic logs found. Run: python tools/seed_data.py")
        return []
    with open(path) as f:
        logs = json.load(f)
    if service_name:
        filtered = [
            l for l in logs
            if service_name.lower() in l.get("service", "").lower()
        ]
        if filtered:
            logger.info(f"Found {len(filtered)} logs matching: {service_name}")
            return filtered
    logger.info(f"Returning all {len(logs)} synthetic logs")
    return logs


def build_log_brief_prompt(ticket: dict, logs: list) -> str:
    """Build the Claude prompt for log analysis."""
    log_lines = []
    for l in logs[:30]:
        line = (
            f"[{l.get('timestamp', 'unknown')}] "
            f"{l.get('level', 'INFO')} "
            f"{l.get('service', 'unknown')} — "
            f"{l.get('message', '')}"
        )
        log_lines.append(line)

    log_text = "\n".join(log_lines)
    sanitized_logs = sanitize_log(log_text, max_length=3000)

    service = ticket.get("cmdb_ci", "Unknown")
    if isinstance(service, dict):
        service = service.get("display_value", "Unknown")

    return f"""You are a senior SRE analyzing an active incident.
Based on the ticket details and log data below, produce a structured
Log Brief for the on-call analyst. Be specific and direct.

INCIDENT:
Ticket: {ticket.get('number', 'Unknown')}
Title: {ticket.get('short_description', 'Unknown')}
Description: {ticket.get('description', 'Not provided')[:500]}
Affected System: {service}
Opened: {ticket.get('opened_at', 'Unknown')}

LOG DATA ({len(logs)} entries):
{sanitized_logs}

Write the Log Brief in this EXACT format:

## Log Brief — Auto-Generated
**Ticket:** {ticket.get('number', 'Unknown')}
**Analyzed at:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}
**Log entries reviewed:** {len(logs)}

### Root Error Signal
[The single most specific root cause. Quote the exact error message if visible.]

### Error Pattern
[Memory / Connectivity / Timeout / Authentication / Data / Configuration / Unknown]

### Key Log Evidence
- [Most important log line with timestamp and exact message]
- [Second most important evidence]
- [Third piece of evidence or 'No additional evidence found']

### Affected Components
[Specific services, databases, or integrations showing errors]

### Recommended First Actions
1. [Most specific and actionable first step]
2. [Second step]
3. [Third step]

### Confidence Level
[HIGH / MEDIUM / LOW] — [One sentence explaining why]

---
*Auto-generated by Log Harvester Agent. Always verify before acting.*"""


class LogHarvester:
    """
    Main agent class for log harvesting and incident brief generation.

    USAGE:
      python agents/log_harvester.py --test
      python agents/log_harvester.py --ticket INC0000018
      python agents/log_harvester.py
    """

    def __init__(self, config: dict):
        self.config = config
        self.snow = ServiceNowClient(config)
        self.ai = anthropic.Anthropic(api_key=config["anthropic_key"])
        self.db = MetricsDB(config.get("db_path", "data/metrics.db"))
        self.dry_run = config.get("dry_run", True)
        self.model = config.get("ai_model", "claude-sonnet-4-6")
        self.max_tokens = config.get("ai_max_tokens", 1000)
        logger.info(
            f"LogHarvester ready | "
            f"dry_run={self.dry_run} | "
            f"model={self.model}"
        )

    def fetch_logs(self, service_name: str, opened_at: str = "") -> list:
        """
        Fetch logs for the affected service.
        Uses Dynatrace if configured, otherwise uses synthetic data.
        PRODUCTION: Replace this method body with real API calls.
        """
        dt_base = self.config.get("dt_base", "")
        dt_token = self.config.get("dt_token", "")

        if not dt_base or not dt_token:
            logger.info("No Dynatrace config — using synthetic logs")
            return load_synthetic_logs(service_name)

        headers = {"Authorization": f"Api-Token {dt_token}"}
        logs = []

        try:
            logger.info(f"Querying Dynatrace problems for: {service_name}")
            resp = requests.get(
                f"{dt_base}/api/v2/problems",
                params={"pageSize": 10, "problemSelector": "status(OPEN)"},
                headers=headers,
                timeout=30
            )
            if resp.ok:
                problems = resp.json().get("problems", [])
                logger.info(f"Dynatrace returned {len(problems)} problems")
                for p in problems:
                    affected = p.get("affectedEntities", [])
                    entity_name = (
                        affected[0].get("name", service_name)
                        if affected else service_name
                    )
                    logs.append({
                        "timestamp": str(p.get("startTime", "")),
                        "level": "ERROR",
                        "service": entity_name,
                        "message": (
                            f"DYNATRACE PROBLEM: {p.get('title', 'Unknown')} | "
                            f"Impact: {p.get('impactLevel', 'Unknown')} | "
                            f"Status: {p.get('status', 'Unknown')}"
                        )
                    })
            else:
                logger.warning(f"Dynatrace problems API: {resp.status_code}")
        except Exception as e:
            logger.error(f"Dynatrace problems query failed: {e}")

        try:
            logger.info("Querying Dynatrace events...")
            resp = requests.get(
                f"{dt_base}/api/v2/events",
                params={"pageSize": 20},
                headers=headers,
                timeout=30
            )
            if resp.ok:
                events = resp.json().get("events", [])
                logger.info(f"Dynatrace returned {len(events)} events")
                for e in events:
                    entity = e.get("entityId", {})
                    logs.append({
                        "timestamp": str(e.get("startTime", "")),
                        "level": "WARN",
                        "service": entity.get("name", service_name),
                        "message": (
                            f"DYNATRACE EVENT: {e.get('title', 'Unknown')} | "
                            f"Type: {e.get('eventType', 'Unknown')}"
                        )
                    })
            else:
                logger.warning(f"Dynatrace events API: {resp.status_code}")
        except Exception as e:
            logger.error(f"Dynatrace events query failed: {e}")

        if logs:
            logger.info(f"Using {len(logs)} real Dynatrace entries")
            return logs

        logger.warning("Dynatrace returned no data — falling back to synthetic")
        return load_synthetic_logs(service_name)

    def generate_brief(self, ticket: dict, logs: list) -> str:
        """Send ticket and logs to Claude and get back a Log Brief."""
        prompt = build_log_brief_prompt(ticket, logs)
        logger.info(f"Sending {len(logs)} log entries to Claude...")
        message = self.ai.messages.create(
            model=self.model,
            max_tokens=self.max_tokens,
            messages=[{"role": "user", "content": prompt}]
        )
        return message.content[0].text

    def process_incident(self, ticket_sys_id: str) -> bool:
        """
        Main entry point. Fetches logs and attaches Log Brief to ticket.
        """
        start = time.time()
        logger.info(f"Starting Log Harvest for: {ticket_sys_id}")

        ticket = self.snow.get_incident(ticket_sys_id)
        if not ticket:
            logger.error(f"Ticket not found: {ticket_sys_id}")
            return False

        number = ticket.get("number", "UNKNOWN")
        service = ticket.get("cmdb_ci", "Unknown")
        if isinstance(service, dict):
            service = service.get("display_value", "Unknown")

        logger.info(f"Processing: {number} | Service: {service}")

        logs = self.fetch_logs(service, ticket.get("opened_at", ""))

        if not logs:
            logger.warning(f"No logs found for {number}")
            brief = (
                "## Log Brief — Auto-Generated\n\n"
                "No log data found for this service in the incident window.\n\n"
                "### Recommended First Actions\n"
                "1. Check monitoring dashboards manually\n"
                "2. Contact the service owner for recent changes\n"
                "3. Review server-level logs directly\n\n"
                "---\n*Log Harvester found no matching log data.*"
            )
        else:
            brief = self.generate_brief(ticket, logs)

        success = self.snow.add_work_note(ticket_sys_id, brief)
        duration_ms = round((time.time() - start) * 1000)

        self.db.log_run(
            agent_name="LogHarvester",
            ticket_number=number,
            trigger_type="manual",
            input_summary=f"Service: {service} | Logs: {len(logs)}",
            output_summary="Log Brief attached" if success else "FAILED",
            success=success,
            duration_ms=duration_ms,
            minutes_saved=MINUTES_SAVED_PER_RUN if success else 0,
        )

        status = "SUCCESS" if success else "FAILED"
        logger.info(
            f"Log Harvest {status} for {number} | "
            f"Duration: {duration_ms}ms"
        )
        return success

    def run_test(self) -> None:
        """
        Test the full agent pipeline using synthetic data.
        No real ServiceNow ticket or monitoring tool needed.
        """
        logger.info("=" * 60)
        logger.info("LOG HARVESTER — Test Run (Synthetic Data)")
        logger.info("=" * 60)

        test_ticket = {
            "sys_id": "syn008",
            "number": "INC0001008",
            "short_description": "Payment service OOM — restarted 3 times",
            "description": (
                "The payment processing service has restarted 3 times "
                "today due to OutOfMemoryError: Java heap space. "
                "Each restart causes 4-5 minute outages."
            ),
            "cmdb_ci": "payment-service-prod",
            "opened_at": "2025-06-10 13:00:00",
            "priority": "1",
        }

        logger.info(f"Test ticket: {test_ticket['number']}")
        logger.info(f"Service: {test_ticket['cmdb_ci']}")

        logs = self.fetch_logs(
            test_ticket["cmdb_ci"],
            test_ticket["opened_at"]
        )
        logger.info(f"Logs fetched: {len(logs)}")

        if not logs:
            logger.error(
                "No logs loaded. Run: python tools/seed_data.py first."
            )
            return

        brief = self.generate_brief(test_ticket, logs)

        print("\n" + "=" * 60)
        print("GENERATED LOG BRIEF:")
        print("=" * 60)
        print(brief)
        print("=" * 60)
        logger.info("Test complete.")


